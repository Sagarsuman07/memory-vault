from typing import Annotated

from langgraph.graph.message import add_messages
from typing_extensions import TypedDict


# ============================================================
# Backend-Controlled Memory Scope
# ============================================================

class MemoryScope(TypedDict):
    """
    Backend-controlled authorization scope for memory access.

    IMPORTANT:
    - Created by the application.
    - Never created or modified by the LLM.
    - Used by tools to enforce memory isolation.
    """

    user_id: str

    # "all"    -> all memories belonging to user_id
    # "memory" -> only memory_ids belonging to user_id
    scope_type: str

    # None for global scope.
    # List of authorized memory IDs for memory scope.
    memory_ids: list[str] | None


# ============================================================
# Agent State
# ============================================================

class AgentState(TypedDict, total=False):

    # ========================================================
    # Persisted Conversation
    # ========================================================

    messages: Annotated[
        list,
        add_messages,
    ]

    # ========================================================
    # Request Information
    # ========================================================

    user_id: str
    question: str

    # Self-contained version of the current question.
    rewritten_question: str

    # "all" or "memory"
    scope: str

    # Selected memory when scope == "memory"
    memory_id: str | None

    # Backend-controlled authorization scope
    memory_scope: MemoryScope

    # ========================================================
    # Phase 1 — Bounded Conversation Context
    # ========================================================

    # One rolling summary of older completed Q&A rounds.
    older_rounds_summary: str

    # Number of completed Q&A rounds represented by the summary.
    summarized_round_count: int

    # Compact latest completed Q&A rounds; excludes tool messages.
    recent_conversation: list

    # Conversation provenance is metadata, not raw tool output.
    # Each item contains an earlier answer and its used memory IDs.
    conversation_provenance: list

    # Current query intent, e.g. chit_chat, app_help, memory_lookup.
    intent: str

    # False routes directly to answer_node; True uses the agent/tools.
    needs_tools: bool

    # Generated by understand_query for direct-answer requests.
    direct_answer: str

    # Only IDs from cited previous answers may be carried forward.
    direct_answer_memory_ids: list

    # ========================================================
    # Final Answer
    # ========================================================

    final_answer: str

    # ========================================================
    # Retrieval Sources
    # ========================================================

    # Memory-level sources actually returned by search_memories.
    # One entry per memory.
    retrieval_sources: list

    # ========================================================
    # Agent Routing
    # ========================================================

    # True when the latest agent response requested tools.
    agent_has_tool_calls: bool

    # ========================================================
    # Tool Tracking
    # ========================================================

    # All requested tool calls.
    tool_calls: list

    # Number of tools actually executed in this request.
    tool_call_count: int

    # True if a tool call was blocked.
    tool_limit_reached: bool

    # Tool calls requested but not executed.
    blocked_tool_calls: list
